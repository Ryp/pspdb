// The C helpers run kirk7 in place; go through a scratch copy so the callee
// never sees overlapping buffers.
fn kirk7InPlace(buf: []u8, key: u8) void {
    var tmp: [0xA0]u8 = undefined;
    @memcpy(tmp[0..buf.len], buf);
    kirk.kirk7(buf, tmp[0..buf.len], key);
}

fn expandSeed(seed: *const [16]u8, key: u8, bonus: ?*const [16]u8) [0x90]u8 {
    var out: [0x90]u8 = undefined;
    var i: usize = 0;
    while (i < out.len) : (i += 0x10) {
        @memcpy(out[i..][0..16], seed);
        out[i] = @intCast(i / 0x10);
    }
    kirk7InPlace(&out, key);
    if (bonus) |b| {
        for (&out, 0..) |*v, j| v.* ^= b[j % 0x10];
    }
    return out;
}

// xorbuf is the 0x80 bytes of the expanded seed starting at +0x10.
fn decryptKirkHeader(out: []u8, in: *const [0x40]u8, xorbuf: *const [0x80]u8, key: u8) void {
    for (0..0x40) |i| out[i] = in[i] ^ xorbuf[i];
    kirk7InPlace(out[0..0x40], key);
    for (0..0x40) |i| out[i] ^= xorbuf[0x40 + i];
}

fn decryptKirkHeaderType0(out: []u8, in: []const u8, xorbuf: *const [0x90]u8, key: u8) void {
    for (0..0x70) |i| out[i] = in[i] ^ xorbuf[i + 0x14];
    kirk7InPlace(out[0..0x70], key);
    for (0..0x70) |i| out[i] ^= xorbuf[i + 0x20];
}

// Flat PRXType0/1 layout (C struct is all u8 arrays, no padding):
// tag@0 sha1@4(0x14) unused@0x18(0x28) kirkBlock@0x40(0x90) prxHeader@0xD0(0x80)
fn loadType01(prx: []const u8) [psp_header_size]u8 {
    var s: [psp_header_size]u8 = undefined;
    @memcpy(s[0..4], prx[0xD0..0xD4]);
    @memcpy(s[4..0x18], prx[0xD4..0xE8]);
    @memcpy(s[0x18..0x40], prx[0xE8..0x110]);
    @memcpy(s[0x40..0x80], prx[0x110..0x150]);
    @memcpy(s[0x80..0xD0], prx[0x80..0xD0]);
    @memcpy(s[0xD0..0x150], prx[0..0x80]);
    return s;
}

// Flat PRXType2/5/6 layout: tag@0 empty@4(0x58; type 6: empty 0x38 + ecdsa
// tail@0x3C 0x20) id@0x5C(0x10) sha1@0x6C(0x14) kirkHeader@0x80(0x40)
// kirkMetadata@0xC0(0x10) prxHeader@0xD0(0x80)
fn loadType256(prx: []const u8, type6: bool) [psp_header_size]u8 {
    var s: [psp_header_size]u8 = undefined;
    @memcpy(s[0..4], prx[0xD0..0xD4]);
    @memset(s[4..0x5C], 0);
    if (type6) @memcpy(s[0x3C..0x5C], prx[0x10C..0x12C]);
    @memcpy(s[0x5C..0x6C], prx[0x140..0x150]);
    @memcpy(s[0x6C..0x80], prx[0x12C..0x140]);
    // kirk header is split between 0x80->0xB0 and 0xC0->0xD0
    @memcpy(s[0x80..0xB0], prx[0x80..0xB0]);
    @memcpy(s[0xB0..0xC0], prx[0xC0..0xD0]);
    @memcpy(s[0xC0..0xD0], prx[0xB0..0xC0]);
    @memcpy(s[0xD0..0x150], prx[0..0x80]);
    return s;
}

fn sha1Type256(s: *const [psp_header_size]u8, xor16: []const u8) [20]u8 {
    var ctx = Sha1.init(.{});
    ctx.update(s[0..4]);
    ctx.update(xor16[0..0x10]);
    ctx.update(s[4..0x6C]); // empty (+ ecdsa tail for type 6) + id
    ctx.update(s[0x80..0x150]); // kirkHeader, kirkMetadata, prxHeader
    var d: [20]u8 = undefined;
    ctx.final(&d);
    return d;
}

fn sha1Type01(s: *const [psp_header_size]u8, xor14: []const u8) [20]u8 {
    var ctx = Sha1.init(.{});
    ctx.update(xor14[0..0x14]);
    ctx.update(s[0x18..0x150]); // unused, kirkBlock, prxHeader
    var d: [20]u8 = undefined;
    ctx.final(&d);
    return d;
}

fn sameBuf(a: []const u8, b: []const u8) bool {
    return @intFromPtr(a.ptr) == @intFromPtr(b.ptr);
}

fn runKirk(out: []u8, size: usize) i32 {
    if (kirk.bufferCopyWithRange(out[0..size], out[header_offset..size], kirk_cmd_decrypt_private) != 0) return -4;
    return 0;
}

fn decryptType0(in: []const u8, out: []u8, size: usize) i32 {
    const decrypt_size: i32 = @bitCast(readLe32(in, 0xB0));
    const pti = getTagInfo(readLe32(in, 0xD0)) orelse return -1;

    // The key table is the pre-decrypted seed; no expansion needed.
    const xorbuf: [0x90]u8 = pti.key.*;
    const s = loadType01(in);

    const sha1 = sha1Type01(&s, &xorbuf);
    if (!std.mem.eql(u8, &sha1, s[4..0x18])) return -3;

    if (!sameBuf(in, out)) @memcpy(out[0..size], in[0..size]);

    @memcpy(out[header_offset..][0..kirk_header_size], s[0x40..0xD0]);
    @memcpy(out[header_offset + kirk_header_size ..][0..prx_header_size], s[0xD0..0x150]);
    decryptKirkHeaderType0(out[header_offset..], s[0x40..0xD0], &xorbuf, pti.code);

    if (runKirk(out, size) != 0) return -4;
    return decrypt_size;
}

fn decryptType1(in: []const u8, out: []u8, size: usize) i32 {
    const decrypt_size: i32 = @bitCast(readLe32(in, 0xB0));
    const pti = getTagInfo(readLe32(in, 0xD0)) orelse return -1;

    const xorbuf: [0x90]u8 = pti.key.*;
    var s = loadType01(in);
    kirk7InPlace(s[0x10..0xB0], pti.code); // sha1+0xC, 0xA0 bytes

    const sha1 = sha1Type01(&s, &xorbuf);
    if (!std.mem.eql(u8, &sha1, s[4..0x18])) return -3;

    if (!sameBuf(in, out)) @memcpy(out[0..size], in[0..size]);

    @memcpy(out[header_offset..][0..kirk_header_size], s[0x40..0xD0]);
    @memcpy(out[header_offset + kirk_header_size ..][0..prx_header_size], s[0xD0..0x150]);
    decryptKirkHeaderType0(out[header_offset..], s[0x40..0xD0], &xorbuf, pti.code);

    if (runKirk(out, size) != 0) return -4;
    return decrypt_size;
}

// Writes the reconstructed KIRK CMD1 header (metadata at +0x70, PRX header at
// +0x90, decrypted header at +0), sets mode (and ecdsa_hash) and runs KIRK.
fn finishType256(s: *const [psp_header_size]u8, in: []const u8, out: []u8, size: usize, xorbuf: *const [0x90]u8, code: u8, type6: bool) i32 {
    if (!sameBuf(in, out)) @memcpy(out[0..size], in[0..size]);

    const header = out[header_offset..][0..kirk_header_size];
    @memset(header, 0);
    if (type6) @memcpy(header[0x40..0x60], s[0x3C..0x5C]);
    @memcpy(header[0x70..0x80], s[0xC0..0xD0]);
    @memcpy(out[header_offset + kirk_header_size ..][0..prx_header_size], s[0xD0..0x150]);
    decryptKirkHeader(header, s[0x80..0xC0], xorbuf[0x10..0x90], code);
    std.mem.writeInt(u32, header[0x60..0x64], 1, .little);
    if (type6) header[0x64] = 1;

    return runKirk(out, size);
}

fn decryptType2(in: []const u8, out: []u8, size: usize, type4: bool) i32 {
    const decrypt_size: i32 = @bitCast(readLe32(in, 0xB0));
    const pti = getTagInfo2(readLe32(in, 0xD0)) orelse return -1;

    // The zero-area check over 0xD4..0x12C is intentionally absent upstream.
    const xorbuf = expandSeed(pti.key, pti.code, null);

    var s = loadType256(in, false);
    kirk7InPlace(s[0x5C..0xBC], pti.code); // id, 0x60 bytes
    // uOFW mesg_led.c: type 4 keeps these 0x58 bytes instead of zeroing them.
    if (type4) @memcpy(s[4..0x5C], in[0xD4..0x12C]);

    const sha1 = sha1Type256(&s, &xorbuf);
    if (!std.mem.eql(u8, &sha1, s[0x6C..0x80])) return -3;

    if (finishType256(&s, in, out, size, &xorbuf, pti.code, false) != 0) return -4;
    return decrypt_size;
}

fn decryptType5(in: []const u8, out: []u8, size: usize, seed: ?[]const u8) i32 {
    const decrypt_size: i32 = @bitCast(readLe32(in, 0xB0));
    const tag = readLe32(in, 0xD0);
    var pti = getTagInfo2(tag);
    // The contextual POPS recipe is never visible to standalone or other types.
    if (pti == null and seed != null and tag == pops_tag.tag) pti = &pops_tag;
    const p = pti orelse return -1;

    // The C reads 16 bytes from `seed` unconditionally; a shorter slice has no
    // C equivalent, so it is treated as "no usable recipe".
    var seed16: ?*const [16]u8 = null;
    if (seed) |sd| {
        if (sd.len < 16) return -1;
        seed16 = sd[0..16];
    }

    const xorbuf = expandSeed(p.key, p.code, seed16);

    // decrypt_mode 23 takes precedence over the tag's fixed XOR.
    const xor1: ?*const [16]u8 = if (in[0x7C] == 23) &xor_91E0A9AD else p.seed;

    var s = loadType256(in, false);

    // First step: decrypt kirk header + SHA1.
    var data: [0x50]u8 = undefined;
    @memcpy(data[0..0x40], s[0x80..0xC0]);
    @memcpy(data[0x40..0x50], s[0x6C..0x7C]);
    for (&data, 0..) |*v, i| {
        if (xor1) |x| v.* ^= x[i % 0x10];
        if (seed16) |x| v.* ^= x[i % 0x10];
    }
    kirk7InPlace(&data, p.code);
    @memcpy(s[0x80..0xC0], data[0..0x40]);
    @memcpy(s[0x6C..0x7C], data[0x40..0x50]);

    // Second step: XOR then decrypt id through to the kirk header. The 0x60
    // span overlaps sha1/kirkHeader and is applied to the already-updated bytes.
    if (xor1) |x| {
        for (0..0x60) |i| s[0x5C + i] ^= x[i % 0x10];
    }
    kirk7InPlace(s[0x5C..0xBC], p.code);

    const sha1 = sha1Type256(&s, &xorbuf);
    if (!std.mem.eql(u8, &sha1, s[0x6C..0x80])) return -3;

    if (finishType256(&s, in, out, size, &xorbuf, p.code, false) != 0) return -4;
    return decrypt_size;
}

fn decryptType6(in: []const u8, out: []u8, size: usize) i32 {
    const decrypt_size: i32 = @bitCast(readLe32(in, 0xB0));
    const pti = getTagInfo2(readLe32(in, 0xD0)) orelse return -1;

    const xorbuf = expandSeed(pti.key, pti.code, null);

    var s = loadType256(in, true);
    kirk7InPlace(s[0x5C..0xBC], pti.code);

    const sha1 = sha1Type256(&s, &xorbuf);
    if (!std.mem.eql(u8, &sha1, s[0x6C..0x80])) return -3;

    if (finishType256(&s, in, out, size, &xorbuf, pti.code, true) != 0) return -4;
    return decrypt_size;
}

/// `pspDecryptPRX(inbuf, outbuf, size, seed)`. `in` and `out` may be the same
/// memory. Both must hold at least `size` bytes (the C trusts the caller; a
/// shorter slice returns -2). `seed`, when present, supplies the 16-byte POPS
/// title seed (a shorter slice is rejected with -1 when a type-5 recipe needs it).
pub fn decryptPrx(in: []const u8, out: []u8, size: u32, seed: ?[]const u8) i32 {
    if (size < psp_header_size) return -2;
    const n: usize = size;
    if (in.len < n or out.len < n) return -2;

    const tag = readLe32(in, 0xD0);
    if (getTagInfo2(tag)) |pti| {
        if (pti.kind != 0) {
            // Explicit recipes are authoritative, including failures. A type-2
            // CMAC failure must never retry as type 6 or external type 9.
            return switch (pti.kind) {
                2 => decryptType2(in, out, n, false),
                5 => decryptType5(in, out, n, seed),
                6 => decryptType6(in, out, n),
                else => -1,
            };
        }
    }

    // Legacy entries without an authoritative recipe still need layout probing.
    // Once a layout's SHA matches, any KIRK integrity failure is terminal.
    var res = decryptType0(in, out, n);
    if (res == -4 or res >= 0) return res;

    res = decryptType1(in, out, n);
    if (res == -4 or res >= 0) return res;

    res = decryptType2(in, out, n, false);
    if (res == -4 or res >= 0) return res;

    res = decryptType5(in, out, n, seed);
    if (res == -4 or res >= 0) return res;

    res = decryptType6(in, out, n);
    if (res == -4 or res >= 0) return res;

    return decryptType2(in, out, n, true);
}

/// `pspdb_prx_decode`. `output` doubles as the reconstruction workspace and
/// must hold at least `input.len` bytes; it must not overlap `input`.
pub fn prxDecode(input: []const u8, output: []u8) i32 {
    if (input.len < psp_header_size or input.len > std.math.maxInt(i32) or
        output.len < input.len) return -1;
    if (!std.mem.eql(u8, input[0..4], "~PSP") and !std.mem.eql(u8, input[0..8], "PSPsysGP")) return -1;

    const expected = readLe32(input, 0xB0);
    if (expected == 0 or expected > input.len) return -2;

    // Known recipes fail terminally; KIRK checks CMAC or both type-6 ECDSA
    // signatures before releasing plaintext. No payload-only fallback.
    const result = decryptPrx(input, output, @intCast(input.len), null);
    // A matched PRX header followed by failed KIRK integrity is terminal.
    if (result == -4) return -5;
    if (result < 0) return -3;
    if (@as(u32, @intCast(result)) != expected) return -4;
    return result;
}
