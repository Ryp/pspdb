const Error = error{ Psar, Sink } || std.mem.Allocator.Error;

fn le32(bytes: []const u8, offset: usize) u32 {
    return std.mem.readInt(u32, bytes[offset..][0..4], .little);
}

fn allDigits(s: []const u8) bool {
    for (s) |ch| {
        if (ch < '0' or ch > '9') return false;
    }
    return true;
}

fn startsWith(s: []const u8, prefix: []const u8) bool {
    return std.mem.startsWith(u8, s, prefix);
}

fn sext16(x: u32) u32 {
    return @bitCast(@as(i32, @as(i16, @bitCast(@as(u16, @truncate(x))))));
}

fn addressRange(address: u32, base: u32, size: usize, length: usize) bool {
    return address >= base and @as(usize, address - base) <= size and length <= size - (address - base);
}

/// Bounded string (names and paths are < 160 bytes by construction).
const Str = struct {
    buf: [512]u8 = undefined,
    len: usize = 0,

    fn from(parts: []const []const u8) Str {
        var s: Str = .{};
        for (parts) |p| {
            @memcpy(s.buf[s.len..][0..p.len], p);
            s.len += p.len;
        }
        return s;
    }

    fn slice(self: *const Str) []const u8 {
        return self.buf[0..self.len];
    }
};

const Sink = struct {
    context: ?*anyopaque,
    emit: Emit,

    fn file(self: Sink, name: []const u8, bytes: []const u8) Error!void {
        if (self.emit(self.context, name.ptr, name.len, bytes.ptr, bytes.len, 0) != 0) return error.Sink;
    }

    fn directory(self: Sink, name: []const u8) Error!void {
        if (self.emit(self.context, name.ptr, name.len, null, 0, 1) != 0) return error.Sink;
    }

    fn parents(self: Sink, name: []const u8) Error!void {
        for (name, 0..) |ch, i| {
            if (ch == '/') try self.directory(name[0..i]);
        }
    }
};

// zlib framing for PSAR records (raw=true, windowBits 15), gzip for payloads (31).
fn gunzip(input: []const u8, out: []u8, consumed: ?*u32, raw: bool) i32 {
    if (input.len < 2) return -1;
    var stream: c.z_stream = std.mem.zeroes(c.z_stream);
    if (c.inflateInit2_(&stream, @as(c_int, if (raw) 15 else 31), c.zlibVersion(), @sizeOf(c.z_stream)) != c.Z_OK) return -1;
    stream.next_in = @constCast(input.ptr);
    stream.avail_in = @intCast(input.len);
    stream.next_out = out.ptr;
    stream.avail_out = @intCast(out.len);
    const status = c.inflate(&stream, c.Z_FINISH);
    const written = stream.total_out;
    const used = stream.total_in;
    _ = c.inflateEnd(&stream);
    if (status != c.Z_STREAM_END or written > std.math.maxInt(i32)) return -1;
    if (consumed) |p| p.* = @truncate(used);
    return @intCast(written);
}

// `pspdb_psar_hash`: legacy custom SHA-256 == SHA-224 (28 bytes written).
fn hash2(custom: bool, a: []const u8, b: []const u8, out: []u8) void {
    if (custom) {
        var h = Sha224.init(.{});
        h.update(a);
        h.update(b);
        h.final(out[0..28]);
    } else {
        var h = Sha256.init(.{});
        h.update(a);
        h.update(b);
        h.final(out[0..32]);
    }
}

// ------------------------------------------------------------------ DES-CBC

fn permute(x: u64, n_in: u8, table: []const u8) u64 {
    var r: u64 = 0;
    for (table) |p| r = (r << 1) | ((x >> @intCast(n_in - p)) & 1);
    return r;
}

fn rotl28(x: u32, n: u5) u32 {
    return ((x << n) | (x >> (28 - n))) & 0xfffffff;
}

fn desSubkeys(key: [8]u8) [16]u64 {
    const k = permute(std.mem.readInt(u64, &key, .big), 64, &des_pc1);
    var cc: u32 = @intCast(k >> 28);
    var dd: u32 = @intCast(k & 0xfffffff);
    var ks: [16]u64 = undefined;
    for (des_shifts, 0..) |s, i| {
        cc = rotl28(cc, @intCast(s));
        dd = rotl28(dd, @intCast(s));
        ks[i] = permute((@as(u64, cc) << 28) | dd, 56, &des_pc2);
    }
    return ks;
}

fn desBlockDecrypt(ks: *const [16]u64, block: u64) u64 {
    const x = permute(block, 64, &des_ip);
    var l: u32 = @intCast(x >> 32);
    var r: u32 = @truncate(x);
    var round: usize = 16;
    while (round > 0) {
        round -= 1;
        const k = ks[round];
        const t = std.math.rotr(u32, r, 1);
        const last = std.math.rotl(u32, r, 1) & 0x3f;
        var f: u32 = 0;
        inline for (0..8) |i| {
            const g: u32 = if (i < 7) (t >> (26 - 4 * i)) & 0x3f else last;
            const kk: u32 = @intCast((k >> (42 - 6 * i)) & 0x3f);
            f |= des_sp[i][g ^ kk];
        }
        const nl = r;
        r = l ^ f;
        l = nl;
    }
    return permute((@as(u64, r) << 32) | l, 64, &des_fp);
}

/// OpenSSL DES-CBC decrypt, padding off, in place; `data.len % 8 == 0`.
fn desCbcDecrypt(data: []u8, key: [8]u8, iv: [8]u8) void {
    const ks = desSubkeys(key);
    var prev = std.mem.readInt(u64, &iv, .big);
    var i: usize = 0;
    while (i < data.len) : (i += 8) {
        const cipher = std.mem.readInt(u64, data[i..][0..8], .big);
        std.mem.writeInt(u64, data[i..][0..8], desBlockDecrypt(&ks, cipher) ^ prev, .big);
        prev = cipher;
    }
}

// ------------------------------------------------------------------ IPL1 / IPL2

fn kirk1block(in: *const [0x1000]u8, out: *[0x1000]u8) i32 {
    var tmp: [0x1040]u8 = @splat(0);
    const decoded = le32(in, 0x70);
    if (decoded < 16 or decoded > 0x1000) return -1;
    @memcpy(tmp[0x40..], in);
    const ret = kirk.bufferCopyWithRange(&tmp, tmp[0x40..], 1);
    if (ret != 0) return ret;
    if (le32(&tmp, 4) > decoded - 16) return -1;
    @memcpy(out, tmp[0..0x1000]);
    return 0;
}

// idx <= 0x3F and 0x7E0 iterations keep idx + 3 <= 65 inside the 68-word table.
fn xorkey(n: u32) u32 {
    return xorkeys[n];
}

fn descramble03g(data: []u8, i: u32) void {
    const idx = (i >> 5) & 0x3F;
    const rot: u5 = @intCast(i & 0x1F);
    const x1 = std.math.rotr(u32, xorkey(idx), rot);
    const x2 = @bitReverse(std.math.rotr(u32, xorkey(idx + 1), rot));
    const x4o = xorkey(idx + 3);
    const x3 = std.math.rotr(u32, xorkey(idx + 2), rot) ^ x4o;
    const x4 = std.math.rotr(u32, x4o, rot);
    const words = [4]u32{ x1, x2, x3, x4 };
    for (words, 0..) |w, k| {
        const cur = std.mem.readInt(u32, data[k * 4 ..][0..4], .little);
        std.mem.writeInt(u32, data[k * 4 ..][0..4], cur ^ w, .little);
    }
}

fn decryptIpl1(in: []const u8, out: []u8, cb_in: usize) i32 {
    if (cb_in == 0 or cb_in % 0x1000 != 0) return -1;
    var cb_out: i32 = 0;
    var xorkey_idx: i64 = -1;
    var off: usize = 0;
    var remaining = cb_in;
    while (remaining >= 0x1000) {
        const src: *const [0x1000]u8 = in[off..][0..0x1000];
        const dst: *[0x1000]u8 = out[off..][0..0x1000];
        if (src[0x62] == 1) {
            var dec: [0x1000]u8 = src.*;
            dec[0x62] = 0;
            if (xorkey_idx == -1) {
                var i: u32 = 0;
                while (i < 0x7E0) : (i += 1) {
                    descramble03g(&dec, i);
                    if (kirk1block(&dec, dst) == 0) break;
                    @memcpy(dec[0..16], src[0..16]);
                }
                if (i == 0x7E0) return -1;
                xorkey_idx = i;
            } else {
                descramble03g(&dec, @intCast(xorkey_idx));
                if (kirk1block(&dec, dst) != 0) return -1;
            }
        } else if (kirk1block(src, dst) != 0) return -1;
        off += 0x1000;
        remaining -= 0x1000;
        cb_out += 0x1000;
    }
    return cb_out;
}

fn linearizeIpl2(in: []const u8, out: []u8, cb_in: i32, start_addr: *u32) i32 {
    if (cb_in <= 0 or @rem(cb_in, 0x1000) != 0) return -1;
    var next_addr: u32 = 0;
    var cb_out: i32 = 0;
    var in_off: usize = 0;
    var out_off: usize = 0;
    var remaining = cb_in;
    while (remaining > 0) {
        const addr = le32(in, in_off);
        if (addr != next_addr and next_addr != 0) return 0;
        if (next_addr == 0) start_addr.* = addr;
        const count = le32(in, in_off + 4);
        if (count > 0xff0 or addr > std.math.maxInt(u32) - count) return -1;
        next_addr = addr + count;
        @memcpy(out[out_off..][0..count], in[in_off + 0x10 ..][0..count]);
        out_off += count;
        cb_out += @intCast(count);
        in_off += 0x1000;
        remaining -= 0x1000;
    }
    return cb_out;
}

fn decryptIpl3(in: []const u8, out: []u8, cb_in: i32) i32 {
    if (cb_in < 0x90 or cb_in > 1000000 - 0x40) return 0;
    const cb: usize = @intCast(cb_in);
    const declared = le32(in, 0x70);
    if (declared == 0 or declared > cb or declared > 1000000) return 0;
    @memcpy(out[0x40..][0..cb], in[0..cb]);
    // out and in overlap exactly as in the C (out = in - 0x40).
    if (kirk.bufferCopyWithRange(out[0 .. cb + 0x40], out[0x40..][0..cb], 1) != 0) return 0;
    return @intCast(declared);
}

// ------------------------------------------------------------------ stage ciphers

const Mt = struct {
    count: u32,
    state: [624]u32,

    fn next(self: *Mt) u32 {
        const init_count = self.count;
        const prev = self.state[init_count];
        if (self.count >= 623) self.count = 0 else self.count += 1;
        const cur = self.state[self.count];
        var x = (prev & 0x80000000) | (cur & 0x7fffffff);
        x >>= 1;
        const z = if (init_count < 227) self.state[init_count + 397] else self.state[init_count - 227];
        if (cur & 1 != 0) x ^= 0x9908B0DF;
        self.state[init_count] = x ^ z;
        var y = prev ^ (prev >> 11);
        y ^= (y << 7) & 0x9D2C5680;
        y ^= (y << 15) & 0xEFC60000;
        y ^= y >> 18;
        return y;
    }

    fn shuffle(self: *Mt, out: usize, in1: usize, in2: usize, in3: usize, in4: usize) void {
        const a: [4]u32 = self.state[in1..][0..4].*;
        const b: [4]u32 = self.state[in2..][0..4].*;
        const cc: [4]u32 = self.state[in3..][0..4].*;
        const d: [4]u32 = self.state[in4..][0..4].*;
        var t0 = a[0];
        var t1 = a[1];
        var t2 = a[2];
        var t3 = a[3];
        t0 ^= a[0] << 8;
        t1 ^= ((a[0] >> 24) & 0xFF) | (a[1] << 8);
        t2 ^= ((a[1] >> 24) & 0xFF) | (a[2] << 8);
        t3 ^= ((a[2] >> 24) & 0xFF) | (a[3] << 8);
        t0 ^= (b[0] >> 11) & 0xDFFFFFEF;
        t1 ^= (b[1] >> 11) & 0xDDFECB7F;
        t2 ^= (b[2] >> 11) & 0xBFFAFFFF;
        t3 ^= (b[3] >> 11) & 0xBFFFFFF6;
        const t4 = (cc[0] >> 8) | (cc[1] << 24);
        const t5 = (cc[1] >> 8) | (cc[2] << 24);
        const t6 = (cc[2] >> 8) | (cc[3] << 24);
        const t7 = cc[3] >> 8;
        self.state[out + 0] = t0 ^ t4 ^ (d[0] << 18);
        self.state[out + 1] = t1 ^ t5 ^ (d[1] << 18);
        self.state[out + 2] = t2 ^ t6 ^ (d[2] << 18);
        self.state[out + 3] = t3 ^ t7 ^ (d[3] << 18);
    }

    fn sfmtNext(self: *Mt) u32 {
        const cur = self.count;
        if (cur < 624) {
            self.count = cur + 1;
            return self.state[cur];
        }
        var state1: usize = 616;
        var state2: usize = 620;
        var i: usize = 0;
        while (i < 34) : (i += 1) {
            const a0 = i * 4;
            self.shuffle(a0, a0, a0 + 488, state1, state2);
            state1 = state2;
            state2 = a0;
        }
        while (i < 156) : (i += 1) {
            const a0 = i * 4;
            self.shuffle(a0, a0, a0 - 136, state1, state2);
            state1 = state2;
            state2 = a0;
        }
        self.count = 1;
        return self.state[0];
    }

    fn sfmtCertify(self: *Mt) void {
        const parity = [4]u32{ 1, 0, 0, 0x13C9E684 };
        var v0: u32 = 0;
        for (0..4) |i| {
            var s = self.state[i] & parity[i];
            s ^= s >> 16;
            s ^= s >> 8;
            s ^= s >> 4;
            s ^= s >> 2;
            s ^= s >> 1;
            v0 = (v0 ^ s) & 1;
        }
        if (v0 != 0) return;
        for (0..4) |i| {
            const s = parity[i];
            if (s != 0) {
                self.state[i] ^= @as(u32, 0x80000000) >> @intCast(@clz(s ^ (s -% 1)));
                return;
            }
        }
    }

    /// `sfmtInit` with a non-null seed of `seed_size` words (7 or 8).
    fn sfmtInit(self: *Mt, seed: *const [8]u32, seed_size: u32) void {
        const s = &self.state;
        self.count = 624;
        @memset(s, 0x8B8B8B8B);
        const a3: i32 = @intCast(@max(seed_size + 1, 624) - 1);
        var t0: u32 = 0;
        var p1: usize = 0;
        var p2: usize = 306;
        var p3: usize = 623;
        var p4: usize = 317;
        var seed_active = true;
        var seed_pos: usize = 0;
        var t1: i32 = -1;
        while (t1 < a3) : (t1 += 1) {
            var t6 = s[p1] ^ s[p2] ^ s[p3];
            t6 = (t6 ^ (t6 >> 27)) *% 0x19660D;
            s[p2] +%= t6;
            if (seed_active) {
                if (t0 == 0) {
                    t6 +%= seed_size;
                } else {
                    t6 +%= seed[seed_pos];
                    seed_pos += 1;
                    if (@as(u32, @bitCast(t1 + 1)) == seed_size) seed_active = false;
                }
            }
            t6 +%= t0;
            s[p4] +%= t6;
            s[p1] = t6;
            t0 += 1;
            if (t0 >= 624) t0 = 0;
            p1 = (p1 + 1) % 624;
            p2 = (p2 + 1) % 624;
            p3 = (p3 + 1) % 624;
            p4 = (p4 + 1) % 624;
        }
        for (0..624) |_| {
            var t6 = s[p1] +% s[p2] +% s[p3];
            t6 = (t6 ^ (t6 >> 27)) *% 0x5D588B65;
            s[p2] ^= t6;
            t6 -%= t0;
            s[p4] ^= t6;
            s[p1] = t6;
            t0 += 1;
            if (t0 >= 624) t0 = 0;
            p1 = (p1 + 1) % 624;
            p2 = (p2 + 1) % 624;
            p3 = (p3 + 1) % 624;
            p4 = (p4 + 1) % 624;
        }
        self.sfmtCertify();
    }
};

const Cipher = struct {
    custom_sha: bool = false,
    use_sfmt: bool = false,
    empty_round: bool = false,

    /// sha256hmac with data (the NULL-data digest case is handled by `decrypt`).
    fn hmac(self: Cipher, key: []const u8, data: []const u8, out: []u8) void {
        var buf1: [32]u8 = @splat(0);
        var buf2: [64]u8 = key[0..64].*;
        for (&buf2) |*b| b.* ^= 0x36;
        hash2(self.custom_sha, &buf2, data, &buf1);
        for (&buf2) |*b| b.* ^= 0x6A;
        hash2(self.custom_sha, &buf2, buf1[0 .. if (self.custom_sha) 28 else 32], out);
    }

    /// `decrypt(NULL/precomp, ...)`: XOR-stream `data` in place. `key2` is read
    /// from live memory every round (it may overlap `data`, as in the C).
    fn decrypt(self: Cipher, precomp: ?*const [8]u32, key1: []const u8, key2: []const u8, data: []u8) void {
        var words: [8]u32 = @splat(0);
        if (precomp) |p| {
            words = p.*;
        } else {
            var digest: [32]u8 = @splat(0);
            hash2(self.custom_sha, key1[0..64], "", &digest);
            for (&words, 0..) |*w, i| w.* = std.mem.readInt(u32, digest[i * 4 ..][0..4], .little);
        }
        const step: usize = if (self.custom_sha) 28 else 32;
        var ctx: Mt = undefined;
        ctx.count = 0;
        if (self.use_sfmt) {
            ctx.sfmtInit(&words, if (self.custom_sha) 7 else 8);
        } else {
            var i: usize = 0;
            while (i < 624) : (i += 8) {
                @memcpy(ctx.state[i..][0..8], &words);
                if (self.custom_sha) ctx.state[i + 7] = 0;
            }
            for (0..624) |_| _ = ctx.next();
        }
        var pos: usize = 0;
        while (pos < data.len) : (pos += step) {
            var buf1: [16]u32 = undefined;
            if (self.use_sfmt) {
                for (&buf1) |*w| w.* = ctx.sfmtNext();
            } else {
                for (&buf1) |*w| w.* = ctx.next();
                if (self.empty_round) _ = ctx.next();
            }
            var bytes: [64]u8 = undefined;
            for (buf1, 0..) |w, i| std.mem.writeInt(u32, bytes[i * 4 ..][0..4], w, .little);
            var hmac2: [32]u8 = @splat(0);
            self.hmac(key2, &bytes, &hmac2);
            const n = @min(step, data.len - pos);
            for (0..n) |j| data[pos + j] ^= hmac2[j];
        }
    }
};

// ------------------------------------------------------------------ syscon keys

fn sysconTable(model: i32) ?*const [0x400]u8 {
    const map = [13]u8{ 0, 0, 1, 2, 3, 4, 0, 5, 0, 6, 0, 7, 0 };
    const tables = [8]?*const [0x400]u8{ null, &sc_secret_01, &sc_secret_02, &sc_secret_03, &sc_secret_go, &sc_secret_03, &sc_secret_03, &sc_secret_03 };
    if (model >= 13) return null;
    return tables[map[@intCast(model)]];
}

fn getSysconIplKey(model: i32, indata: *const [16]u8) [16]u8 {
    var result: [16]u8 = undefined;
    Aes128.initDec(sc_key).decrypt(&result, indata);
    const index: usize = result[8] & 0x3F;
    const table = sysconTable(model) orelse return @splat(0);
    return table[index * 0x10 ..][0..16].*;
}

fn findStage2Keys(stage2: []const u8) i32 {
    if (stage2.len <= 0x18) return -1;
    for (0..stage2.len - 0x18) |i| {
        const w = stage2[i..][0..0x18];
        if (std.mem.eql(u8, w, &ipl02_1) or std.mem.eql(u8, w, &ipl04_1) or std.mem.eql(u8, w, &ipl_xx_1))
            return @intCast(i + 0x18);
    }
    return -1;
}

