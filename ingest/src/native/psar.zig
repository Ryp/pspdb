fn extractIplStages(sink: Sink, gpa: std.mem.Allocator, in_data: []u8, version: i32, load_addr: u32, filename: []const u8) Error!void {
    if (in_data.len < 0x100) return error.Psar;
    const in_size: u32 = @intCast(in_data.len);
    var cipher: Cipher = .{};

    const dec_buf = try gpa.alloc(u8, stage_buffer);
    defer gpa.free(dec_buf);
    const out_buf = try gpa.alloc(u8, stage_buffer);
    defer gpa.free(out_buf);

    const img2_addr: u32 = 0x04100000;
    const kernel_keys_addr: u32 = 0x040FFF00;
    const part2_load_addr: u32 = 0x04000000;

    // Version < 2.60: no scrambling, just decompress stage2 & decrypt stage3.
    if (version < 260) {
        var off: u32 = 0;
        while (off + 8 <= 0x100) : (off += 4) {
            const gzip_hi = le32(in_data, off);
            const gzip_lo = le32(in_data, off + 4);
            if (gzip_hi >> 16 == 0x3C06 and gzip_lo >> 16 == 0x24C6) {
                const gzip_addr = (gzip_hi << 16) +% sext16(gzip_lo);
                if (!addressRange(gzip_addr, load_addr, in_size, 2)) return error.Psar;
                var real_in: u32 = 0;
                var dec_size = gunzip(in_data[gzip_addr - load_addr ..], dec_buf, &real_in, false);
                if (dec_size < 0) return error.Psar;
                var path = Str.from(&.{ out_dir, "/stage2_", filename });
                try sink.file(path.slice(), dec_buf[0..@intCast(dec_size)]);

                if (!addressRange(img2_addr, load_addr, in_size, 0x90)) return error.Psar;
                const s3 = in_data[img2_addr - load_addr ..];
                dec_size = decryptIpl3(s3, out_buf, @intCast(in_size - (img2_addr - load_addr)));
                if (dec_size == 0) return error.Psar;
                path = Str.from(&.{ out_dir, "/stage3_", filename });
                try sink.file(path.slice(), out_buf[0..@intCast(dec_size)]);
                return;
            }
        }
        return error.Psar;
    }

    // Main keys used for unscrambling.
    var key1_off: u32 = 0;
    var key2_off: u32 = 0;
    var img_off: u32 = 0;
    var img_size: u32 = 0;
    var off: u32 = 0;
    while (off < 0x100) : (off += 4) {
        const instr = le32(in_data, off);
        const hi = instr >> 16;
        if (hi == 0x3C06) key1_off = instr << 16;
        if (hi == 0x24C6) key1_off +%= sext16(instr);
        if (hi == 0x3C07) key2_off = instr << 16;
        if (hi == 0x24E7) key2_off +%= sext16(instr);
        if (hi == 0x3C08) img_off = instr << 16;
        if (hi == 0x2508) img_off +%= sext16(instr);
        if (hi == 0x3C09) img_size = instr << 16;
        if (hi == 0x2529) img_size +%= sext16(instr);
        if (instr >> 26 == 0x03) break;
    }
    if (!addressRange(key1_off, load_addr, in_size, 64) or
        !addressRange(key2_off, load_addr, in_size, 64) or
        !addressRange(img_off, load_addr, in_size, img_size) or img_size == 0 or img_size > std.math.maxInt(i32)) return error.Psar;
    if (version >= 310) cipher.empty_round = true;
    if (version >= 380) cipher.custom_sha = true;
    if (version >= 505) cipher.use_sfmt = true;
    if (key1_off == 0 or key2_off == 0 or img_off == 0 or img_size == 0) return error.Psar;

    // 3.30+: locate the pre-IPL-derived key table (only its failure modes are observable).
    if (version >= 330) {
        var o: u32 = 0;
        while (o + 4 <= img_off - load_addr) : (o += 4) {
            if (le32(in_data, o) == 0x27BDE5D0) {
                var hi_i: u32 = 0;
                var lo_i: u32 = 0;
                var o2 = o;
                while (o2 < o + 0x100 and o2 + 4 <= in_size) : (o2 += 4) {
                    const ins = le32(in_data, o2);
                    if (ins >> 16 == 0x3C07) hi_i = ins;
                    if (ins >> 16 == 0x24E4) lo_i = ins;
                }
                if (hi_i == 0 or lo_i == 0) return error.Psar;
                const addr = (hi_i << 16) +% sext16(lo_i);
                if (!addressRange(addr, load_addr, in_size, 0x321)) return error.Psar;
                break;
            }
        }
    }

    // Decrypt and decompress stage2.
    const key_idx = le32(in_data, key1_off - load_addr);
    const precomp: *const [8]u32 = for (&ipl_keys) |*entry| {
        if (entry.index == key_idx) break &entry.key;
    } else return error.Psar; // no pre-IPL dump: C returns 1
    cipher.decrypt(precomp, in_data[key1_off - load_addr ..][0..64], in_data[key2_off - load_addr ..][0..64], in_data[img_off - load_addr ..][0..img_size]);

    var real_in: u32 = 0;
    var dec_size: i32 = gunzip(in_data[img_off - load_addr ..][0..img_size], dec_buf, &real_in, false);
    if (dec_size < 0) return error.Psar;
    var path = Str.from(&.{ out_dir, "/stage2_", filename });
    try sink.file(path.slice(), dec_buf[0..@intCast(dec_size)]);

    // Syscon xor step for the key blob.
    var scxor: [16]u8 = @splat(0);
    const xkeyoff = findStage2Keys(dec_buf[0..@intCast(dec_size)]);
    if (xkeyoff > 0) {
        if (filename.len < 10) return error.Psar;
        const model: i32 = (@as(i32, @as(i8, @bitCast(filename[8]))) - 0x30) * 10 + (@as(i32, @as(i8, @bitCast(filename[9]))) - 0x30);
        if (model < 0) return error.Psar;
        const wide = version > 505 and model > 1;
        if (xkeyoff > dec_size or dec_size - xkeyoff < @as(i32, if (wide) 32 else 16)) return error.Psar;
        const xo: usize = @intCast(xkeyoff);
        var stage2xor: [16]u8 = @splat(0);
        if (wide) stage2xor = dec_buf[xo + 0x10 ..][0..16].*;
        scxor = getSysconIplKey(model, dec_buf[xo..][0..16]);
        for (&scxor, stage2xor) |*a, b| a.* ^= b;
    }

    // Stage3 key locations (inside stage2).
    const stage2_size: u32 = @intCast(dec_size);
    if (stage2_size < 0x44) return error.Psar;
    const stage2 = dec_buf[0..stage2_size];
    var key3_addr: u32 = undefined;
    var key4_addr: u32 = undefined;
    var img2_size: u32 = undefined;
    if (version < 280) {
        const load1_hi = le32(stage2, 0x000C);
        const load1_lo = le32(stage2, 0x0018);
        const load2_hi = le32(stage2, 0x001C);
        const load2_lo = le32(stage2, 0x0040);
        const load_size = le32(stage2, 0x0028);
        if (load1_hi >> 16 == 0x3C02 and load1_lo >> 16 == 0x2446 and
            load2_hi >> 16 == 0x3C02 and load2_lo >> 16 == 0x2447 and
            load_size >> 16 == 0x3409)
        {
            key3_addr = (load1_hi << 16) +% sext16(load1_lo);
            key4_addr = (load2_hi << 16) +% sext16(load2_lo);
            img2_size = load_size & 0xFFFF;
        } else return error.Psar;
    } else {
        var found = false;
        var o: u32 = 0;
        while (o < 0x400 and o + 0x2c <= stage2_size) : (o += 4) {
            var load1_hi = le32(stage2, o + 0x0C);
            var load1_lo = le32(stage2, o + 0x1C);
            var load2_hi = le32(stage2, o + 0x08);
            var load2_lo = le32(stage2, o + 0x14);
            var load_size = le32(stage2, o + 0x28);
            if (load1_hi >> 16 == 0x3C02 and load1_lo >> 16 == 0x2450 and
                load2_hi >> 16 == 0x3C03 and load2_lo >> 16 == 0x2471 and
                load_size >> 16 == 0x3409)
            {
                key3_addr = (load1_hi << 16) +% sext16(load1_lo);
                key4_addr = (load2_hi << 16) +% sext16(load2_lo);
                img2_size = load_size & 0xFFFF;
                found = true;
                break;
            }
            load1_hi = le32(stage2, o + 0x10);
            load1_lo = le32(stage2, o + 0x18);
            load2_hi = le32(stage2, o + 0x04);
            load2_lo = le32(stage2, o + 0x0C);
            load_size = le32(stage2, o + 0x24);
            if (load1_hi >> 16 == 0x3C02 and load1_lo >> 16 == 0x2450 and
                load2_hi >> 16 == 0x3C02 and load2_lo >> 16 == 0x2451 and
                load_size >> 16 == 0x3409)
            {
                key3_addr = (load1_hi << 16) +% sext16(load1_lo);
                key4_addr = (load2_hi << 16) +% sext16(load2_lo);
                img2_size = load_size & 0xFFFF;
                found = true;
                break;
            }
        }
        if (!found) return error.Psar;
    }

    // Kernel keys (used by memlmd).
    var key5_addr: u32 = 0;
    var key6_addr: u32 = 0;
    if (version >= 330) {
        const load1_hi = le32(stage2, 0x18);
        const load1_lo = le32(stage2, 0x20);
        const load2_hi = le32(stage2, 0x0c);
        const load2_lo = le32(stage2, 0x14);
        if (load1_hi >> 16 == 0x3C02 and load1_lo >> 16 == 0x2450 and
            load2_hi >> 16 == 0x3C02 and load2_lo >> 16 == 0x2451)
        {
            key5_addr = (load1_hi << 16) +% sext16(load1_lo);
            key6_addr = (load2_hi << 16) +% sext16(load2_lo);
        }
    }

    cipher.custom_sha = false;
    if (version >= 380) cipher.use_sfmt = true;
    if (key5_addr != 0 and key6_addr != 0) {
        if (!addressRange(key5_addr, part2_load_addr, stage2_size, 64) or
            !addressRange(key6_addr, part2_load_addr, stage2_size, 64) or
            !addressRange(kernel_keys_addr, load_addr, in_size, 256)) return error.Psar;
        const kk = in_data[kernel_keys_addr - load_addr ..][0..256];
        cipher.decrypt(null, stage2[key5_addr - part2_load_addr ..][0..64], stage2[key6_addr - part2_load_addr ..][0..64], kk);
        dec_size = decryptIpl3(kk, out_buf, 256);
        if (dec_size == 0) return error.Psar;
        path = Str.from(&.{ out_dir, "/kkeys_", filename });
        if (dec_size != 16 and dec_size < 32) return error.Psar;
        if (dec_size >= 32) {
            for (0..16) |j| out_buf[j + 0x10] ^= scxor[j];
        }
        try sink.file(path.slice(), out_buf[0..@intCast(dec_size)]);
    }

    // Decrypt, and possibly decompress, stage3.
    if (!addressRange(key3_addr, part2_load_addr, stage2_size, 64) or
        !addressRange(key4_addr, part2_load_addr, stage2_size, 64) or
        !addressRange(img2_addr, load_addr, in_size, img2_size) or img2_size == 0) return error.Psar;
    cipher.decrypt(null, stage2[key3_addr - part2_load_addr ..][0..64], stage2[key4_addr - part2_load_addr ..][0..64], in_data[img2_addr - load_addr ..][0..img2_size]);
    dec_size = decryptIpl3(in_data[img2_addr - load_addr ..], out_buf, @intCast(in_size - (img2_addr - load_addr)));
    if (dec_size == 0) return error.Psar;
    path = Str.from(&.{ out_dir, "/stage3_", filename });
    const ds: usize = @intCast(dec_size);
    if (ds >= 2 and out_buf[0] == 0x1f and out_buf[1] == 0x8b) {
        var real_in2: u32 = 0;
        const decomp = gunzip(out_buf[0..ds], dec_buf, &real_in2, false);
        if (decomp < 0) return error.Psar;
        try sink.file(path.slice(), dec_buf[0..@intCast(decomp)]);
    } else {
        try sink.file(path.slice(), out_buf[0..ds]);
    }
}

// ------------------------------------------------------------------ PSAR walk

fn compressed(p: []const u8) bool {
    return (p.len >= 2 and p[0] == 0x1f and p[1] == 0x8b) or
        (p.len >= 4 and (std.mem.eql(u8, p[0..4], "2RLZ") or std.mem.eql(u8, p[0..4], "KL4E") or std.mem.eql(u8, p[0..4], "KL3E")));
}

// `pspdb_psar_lzr`.
fn lzrMember(input: []const u8, output: []u8, consumed: *usize) i32 {
    consumed.* = 0;
    const member = lzr.decode_raw_member_into(input, output) catch return -1;
    if (member.written > std.math.maxInt(c_int)) return -1;
    consumed.* = member.consumed;
    return @intCast(member.written);
}

fn expand(input: []const u8, output: []u8, used: *usize) Error!usize {
    used.* = 0;
    if (input.len > std.math.maxInt(i32) or output.len > std.math.maxInt(i32)) return error.Psar;
    var result: i32 = -1;
    if (input.len >= 2 and input[0] == 0x1f and input[1] == 0x8b) {
        var count: u32 = 0;
        result = gunzip(input, output, &count, false);
        used.* = count;
    } else if (input.len >= 4 and std.mem.eql(u8, input[0..4], "2RLZ")) {
        result = lzrMember(input[4..], output, used);
        used.* += 4;
    } else if (input.len >= 4 and (std.mem.eql(u8, input[0..4], "KL4E") or std.mem.eql(u8, input[0..4], "KL3E"))) {
        result = kle.decompressKleBoundedMember(output, input[4..], input[2] == '4', used);
        used.* += 4;
    }
    if (result <= 0 or @as(usize, @intCast(result)) > output.len or used.* == 0 or used.* > input.len) return error.Psar;
    return @intCast(result);
}

fn decryptPrx(input: []const u8, output: []u8, size: usize) Error!usize {
    if (size < 0x150 or size > data_size) return error.Psar;
    const result = prx.decryptPrx(input, output, @intCast(size), null);
    if (result <= 0 or @as(usize, @intCast(result)) > size) return error.Psar;
    return @intCast(result);
}

const Context = struct {
    input: []const u8,
    sink: Sink,
    gpa: std.mem.Allocator,
    first: []u8,
    second: []u8,
    tables: [13][]u8 = @splat(@constCast("")),
    cursor: usize = 0,
    overhead: usize = 0,
    psar_version: u8 = 0,
    firmware: i32 = 0,
    table_mode: u8 = 0,
    plaintext: bool = false,

    fn create(gpa: std.mem.Allocator, input: []const u8, sink: Sink) Error!Context {
        const first = try gpa.alloc(u8, data_size);
        errdefer gpa.free(first);
        const second = try gpa.alloc(u8, data_size);
        @memset(first, 0);
        @memset(second, 0);
        return .{ .input = input, .sink = sink, .gpa = gpa, .first = first, .second = second };
    }

    fn deinit(self: *Context) void {
        for (self.tables) |t| self.gpa.free(t);
        self.gpa.free(self.first);
        self.gpa.free(self.second);
    }

    fn range(self: *const Context, offset: usize, length: usize) Error!void {
        if (offset > self.input.len or length > self.input.len - offset) return error.Psar;
    }

    fn block(self: *Context, offset: usize, length: usize, out: []u8) Error!i32 {
        if (length > data_size) return error.Psar;
        const aligned = if (self.plaintext) length else (length + 15) & ~@as(usize, 15);
        if (aligned > data_size) return error.Psar;
        try self.range(offset, aligned);
        if (self.plaintext) {
            @memcpy(out[0..length], self.input[offset..][0..length]);
            return @intCast(length);
        }
        if (aligned < 0x150) return -1;
        @memcpy(out[0..aligned], self.input[offset..][0..aligned]);
        if (self.psar_version != 1) {
            const k1 = [16]u8{ 0xD8, 0x69, 0xB8, 0x95, 0x33, 0x6B, 0x63, 0x34, 0x98, 0xB9, 0xFC, 0x3C, 0xB7, 0x26, 0x2B, 0xD7 };
            const k2 = [16]u8{ 0x0D, 0xA0, 0x90, 0x84, 0xAF, 0x9E, 0xB6, 0xE2, 0xD2, 0x94, 0xF2, 0xAA, 0xEF, 0x99, 0x68, 0x71 };
            var buffer: [20 + 0x130]u8 = @splat(0);
            @memcpy(buffer[20..], self.input[offset + 0x20 ..][0..0x130]);
            if (self.psar_version == 5) {
                for (0..0x130) |i| buffer[20 + i] ^= k1[i & 15];
            }
            std.mem.writeInt(u32, buffer[0..4], 5, .little);
            std.mem.writeInt(u32, buffer[12..16], 0x55, .little);
            std.mem.writeInt(u32, buffer[16..20], 0x130, .little);
            if (kirk.bufferCopyWithRange(&buffer, &buffer, 7) != 0) return -1;
            if (self.psar_version == 5) {
                for (0..0x130) |i| buffer[i] ^= k2[i & 15];
            }
            @memcpy(out[0x20..][0..0x130], buffer[0..0x130]);
        }
        return prx.decryptPrx(out[0..aligned], out[0..aligned], @intCast(aligned), null);
    }

    fn parseHeader(self: *Context) Error!void {
        const input = self.input;
        try self.range(0, 0x30);
        if (!std.mem.eql(u8, input[0..4], "PSAR")) return error.Psar;
        self.plaintext = le32(input, 0x20) == 0x2c333333;
        self.overhead = if (self.plaintext) 0 else 0x150;
        self.psar_version = input[4];
        if ((try self.block(0x10, self.overhead + 0x110, self.first)) != 0x110) return error.Psar;
        self.cursor = 0x10 + self.overhead + 0x110;
        var decoded: i32 = 0;
        if (self.plaintext) {
            decoded = try self.block(self.cursor, le32(self.first, 0x90), self.second);
            if (decoded <= 0) return error.Psar;
            try self.range(self.cursor, @intCast(decoded));
            self.cursor += @intCast(decoded);
        } else if (self.psar_version != 1) {
            decoded = try self.block(self.cursor, self.overhead + 100, self.second);
            if (decoded <= 0) decoded = try self.block(self.cursor, self.overhead + 144, self.second);
            if (decoded <= 0) decoded = try self.block(self.cursor, self.overhead + self.first[0x90] + (@as(usize, self.first[0x91]) << 8), self.second);
            if (decoded <= 0 or @as(usize, @intCast(decoded)) > data_size - 15) return error.Psar;
            const advance = self.overhead + ((@as(usize, @intCast(decoded)) + 15) & ~@as(usize, 15));
            try self.range(self.cursor, advance);
            self.cursor += advance;
        }
        const begin = self.first[0x10..][0..0x100];
        const end = std.mem.indexOfScalar(u8, begin, 0) orelse return error.Psar;
        const full = begin[0..end];
        const version = if (std.mem.lastIndexOfScalar(u8, full, ',')) |comma| full[comma + 1 ..] else "1.00";
        if (version.len != 4 or version[1] != '.' or version[0] < '0' or version[0] > '9' or
            version[2] < '0' or version[2] > '9' or version[3] < '0' or version[3] > '9') return error.Psar;
        const fw: i32 = @as(i32, version[0] - '0') * 100 + @as(i32, version[2] - '0') * 10 + (version[3] - '0');
        self.firmware = fw;
        if (fw >= 380 and fw < 400) {
            self.table_mode = 1;
        } else if (fw >= 400 and fw < 500) {
            self.table_mode = 2;
        } else if (fw >= 500 and fw < 600) {
            self.table_mode = 3;
        } else if (fw >= 610 and fw < 630 and self.psar_version == 5) {
            self.table_mode = 5;
        } else if (fw >= 600 and fw < 700) {
            self.table_mode = 4;
        }
    }

    fn next(self: *Context, name: *Str, expanded: *usize) Error!bool {
        try self.range(self.cursor, 0);
        if (self.input.len - self.cursor <= self.overhead) return false;
        if ((try self.block(self.cursor, self.overhead + 0x110, self.first)) != 0x110) return error.Psar;
        const field = self.first[4..][0..0xfc];
        const end = std.mem.indexOfScalar(u8, field, 0) orelse return error.Psar;
        if (end == 0 or end >= 128) return error.Psar;
        name.* = Str.from(&.{field[0..end]});
        if (le32(self.first, 0x100) != 0) return error.Psar;
        const chunk: usize = le32(self.first, 0x104);
        expanded.* = le32(self.first, 0x108);
        if (expanded.* > data_size) return error.Psar;
        self.cursor += self.overhead + 0x110;
        try self.range(self.cursor, chunk);
        if (expanded.* != 0) {
            const packed_size = try self.block(self.cursor, chunk, self.first);
            if (packed_size <= 10 or @as(usize, @intCast(packed_size)) > data_size or self.first[0] != 0x78 or self.first[1] != 0x9c) return error.Psar;
            const got = gunzip(self.first[0..@intCast(packed_size)], self.second[0..expanded.*], null, true);
            if (got < 0 or @as(usize, @intCast(got)) != expanded.*) return error.Psar;
        }
        self.cursor += chunk;
        return true;
    }

    fn tablePath(table: []const u8, number: []const u8, out: *Str) Error!bool {
        if (number.len < 5) return error.Psar;
        var i: usize = 0;
        while (i + 5 < table.len) : (i += 1) {
            if (!std.mem.eql(u8, table[i..][0..5], number[0..5])) continue;
            const start = i + 6;
            var end = start;
            while (end < table.len and table[end] >= 0x20) end += 1;
            if (end == table.len or end == start or end - start >= 128) return error.Psar;
            var path = Str.from(&.{table[start..end]});
            if (table[i + 5] == '|') {
                if (startsWith(path.slice(), "flash")) {
                    if (path.len < 7) return error.Psar;
                    path = Str.from(&.{ path.buf[0..6], ":/", path.buf[7..path.len] });
                } else if (startsWith(path.slice(), "ipl")) {
                    if (path.len < 4) return error.Psar;
                    path = Str.from(&.{ path.buf[0..3], ":/", path.buf[4..path.len] });
                }
            }
            if (path.len >= 128) return error.Psar;
            out.* = path;
            return true;
        }
        return false;
    }

    fn resolveName(self: *Context, name: *Str) Error!void {
        const s = name.slice();
        if (s.len == 5 and allDigits(s)) {
            const n = std.fmt.parseInt(u32, s, 10) catch unreachable;
            if (n >= 100 or (n >= 10 and self.firmware < 660)) {
                for (self.tables) |t| {
                    if (t.len != 0 and try tablePath(t, name.slice(), name)) return;
                }
                return error.Psar;
            }
        }
        const prefixes = [_][]const u8{ "com:", "01g:", "02g:" };
        for (prefixes, 0..) |p, i| {
            if (startsWith(name.slice(), p) and self.tables[i].len != 0) {
                if (!try tablePath(self.tables[i], name.slice()[4..], name)) return error.Psar;
                return;
            }
        }
    }

    /// `pspDecryptTable(des, second, first, size, psar_version, table_mode)`.
    fn decryptTable(self: *Context, size: usize) i32 {
        if (size == 0 or size % 8 != 0 or self.table_mode >= 6) return -1;
        @memcpy(self.first[0..size], self.second[0..size]);
        const keys = table_keys[self.table_mode];
        desCbcDecrypt(self.first[0..size], keys.key, keys.iv);
        if (self.psar_version == 4) {
            @memcpy(self.second[0..size], self.first[0..size]);
            return @intCast(size);
        }
        const r = prx.decryptPrx(self.first[0..size], self.second[0..size], @intCast(size), null);
        return if (r < 0) -1 else r;
    }

    fn outputPath(self: *Context, name: []const u8, expanded: *usize) Error!Str {
        if (startsWith(name, "flash0:/")) return Str.from(&.{ "F0/", name[8..] });
        if (startsWith(name, "flash1:/")) return Str.from(&.{ "F1/", name[8..] });
        const filenames = [_]struct { []const u8, u8 }{
            .{ "com:00000", 0 }, .{ "01g:00000", 1 }, .{ "02g:00000", 2 }, .{ "00001", 1 },
