//! Pure-Zig port of `psar_native.cpp` (`pspdb_psar_walk`) with everything it
//! compiles in from the pinned pspdecrypt: pspdecrypt_lib.cpp (IPL1 descramble,
//! IPL2 linearisation, DES table decryption), ipl_decrypt.cpp (stage 2/3 and
//! kernel-key extraction) and syscon_ipl_keys.c.
//!
//! Event order, names, directory flags and return codes match the C:
//! 0 success; -1 malformed/transform; -2 allocation; -3 sink refused.
//! -4 (OpenSSL legacy provider missing) has no equivalent: DES-CBC is
//! implemented here, so it is unreachable.
//!
//! Not ported, unreachable from `pspdb_psar_walk`: `decrypt330`/`mt19937Init`
//! (only used with a pre-IPL dump; the walk always passes `preipl_bin ==
//! nullptr`, so an unknown key index returns failure before they would run),
//! hence also the g_newKey/g_xorKey/g_checksum pointers (the 3.30+ scan that
//! fills them is kept because its failure paths are observable).
//!
//! Deliberate allocation differences: the two 1,000,000-byte stage buffers that
//! the C keeps on the stack live on the heap here (allocation failure -> -2).

