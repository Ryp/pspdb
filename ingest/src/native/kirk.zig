//! Pure-Zig port of the decrypt-side subset of libkirk (kirk_engine.c, AES.c
//! CBC/CMAC glue, bn.c, ec.c) as compiled into PSPDB's pspdecrypt.
//!
//! No global state: `kirk_init_prx()` (KIRK1 key schedule only; fuse ids stay
//! zero, PRNG unused) has no equivalent because the tables are constants.
//!
//! Buffers may alias exactly as the C callers alias them (in == out, or
//! out below in). Every CBC loop copies one 16-byte block out of `in` before
//! writing the matching `out` block, which is what the C does.
//!
//! Where the C reads/writes out of bounds (it only validates CMD1), the port
//! returns KIRK_INVALID_SIZE instead; every real caller stays inside bounds.
//!
//! Not ported (unreachable from pspdecrypt/PSPDB callers): CMD0, CMD12, CMD13,
//! CMD14 (PRNG: time + uninitialised stack, not reproducible), CMD16 (needs
//! PRNG and fuse id), CMD1_ex, kirk_init/init2, encrypt/decrypt_kirk16_private.
//! `bufferCopyWithRange` returns -1 (the C default for an unhandled cmd) for them.

