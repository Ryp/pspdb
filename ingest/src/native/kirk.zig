// ------------------------------------------------------------------ AES-CBC (zero IV)

/// AES_cbc_encrypt over `nblocks` full blocks.
fn cbcEncrypt(key: *const [16]u8, dst: []u8, src: []const u8, nblocks: usize) void {
    const ctx = Aes128.initEnc(key.*);
    var prev: [16]u8 = undefined;
    var i: usize = 0;
    while (i < nblocks) : (i += 1) {
        var blk: [16]u8 = src[i * 16 ..][0..16].*;
        if (i != 0) {
            for (&blk, prev) |*b, p| b.* ^= p;
        }
        ctx.encrypt(&prev, &blk);
        dst[i * 16 ..][0..16].* = prev;
    }
}

/// AES_cbc_decrypt over `nblocks` full blocks (the C always does >= 1).
fn cbcDecrypt(key: *const [16]u8, dst: []u8, src: []const u8, nblocks: usize) void {
    const ctx = Aes128.initDec(key.*);
    var prev: [16]u8 = undefined;
    var i: usize = 0;
    while (i < nblocks) : (i += 1) {
        const cur: [16]u8 = src[i * 16 ..][0..16].*;
        var plain: [16]u8 = undefined;
        ctx.decrypt(&plain, &cur);
        if (i != 0) {
            for (&plain, prev) |*b, p| b.* ^= p;
        }
        dst[i * 16 ..][0..16].* = plain;
        prev = cur;
    }
}

fn blocksCeil(size: usize) usize {
    return (size + 15) / 16;
}

fn rd32(buf: []const u8, off: usize) u32 {
    return std.mem.readInt(u32, buf[off..][0..4], .little);
}

fn rdi32(buf: []const u8, off: usize) i32 {
    return std.mem.readInt(i32, buf[off..][0..4], .little);
}

/// `kirk4(out, in, in.len, key_id)`. `in.len` must be a multiple of 16 and
/// `out.len >= in.len`; an invalid key id panics (the C would crash).
pub fn kirk4(out: []u8, in: []const u8, key_id: i32) void {
    const key = kirk47GetKey(key_id) orelse @panic("kirk4: invalid key id");
    const nb = blocksCeil(in.len);
    if (nb * 16 > in.len or nb * 16 > out.len) @panic("kirk4: unaligned size");
    cbcEncrypt(key, out, in, nb);
}

/// `kirk7(out, in, in.len, key_id)`; same constraints as `kirk4`. A zero
/// length still decrypts one block in the C; here that needs 16 bytes of room.
pub fn kirk7(out: []u8, in: []const u8, key_id: i32) void {
    const key = kirk47GetKey(key_id) orelse @panic("kirk7: invalid key id");
    const nb = @max(1, blocksCeil(in.len));
    if (nb * 16 > in.len or nb * 16 > out.len) @panic("kirk7: unaligned size");
    cbcDecrypt(key, out, in, nb);
}

