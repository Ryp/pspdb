// All bn_* operate on big-endian byte strings of length d.len; operands may alias.

fn bnCompare(a: []const u8, b: []const u8) i32 {
    for (a, b) |x, y| {
        if (x < y) return -1;
        if (x > y) return 1;
    }
    return 0;
}

fn bnAdd1(d: []u8, a: []const u8, b: []const u8) u8 {
    var c: u32 = 0;
    var i = d.len;
    while (i > 0) {
        i -= 1;
        const dig: u32 = @as(u32, a[i]) + b[i] + c;
        c = dig >> 8;
        d[i] = @truncate(dig);
    }
    return @intCast(c);
}

fn bnSub1(d: []u8, a: []const u8, b: []const u8) u8 {
    var c: u32 = 1;
    var i = d.len;
    while (i > 0) {
        i -= 1;
        const dig: u32 = @as(u32, a[i]) + 255 - b[i] + c;
        c = dig >> 8;
        d[i] = @truncate(dig);
    }
    return @intCast(1 - c);
}

fn bnReduce(d: []u8, n: []const u8) void {
    if (bnCompare(d, n) >= 0) _ = bnSub1(d, d, n);
}

fn bnAdd(d: []u8, a: []const u8, b: []const u8, n: []const u8) void {
    if (bnAdd1(d, a, b) != 0) _ = bnSub1(d, d, n);
    bnReduce(d, n);
}

fn bnSub(d: []u8, a: []const u8, b: []const u8, n: []const u8) void {
    if (bnSub1(d, a, b) != 0) _ = bnAdd1(d, d, n);
}

fn bnMonMulAddDig(d: []u8, a: []const u8, b: u8, n: []const u8) void {
    const len = d.len;
    const t0: u32 = @as(u32, d[len - 1]) + @as(u32, a[len - 1]) * b;
    const z: u8 = @truncate((0 -% t0) *% inv256[n[len - 1] / 2]);

    var dig: u32 = t0 + @as(u32, n[len - 1]) * z;
    dig >>= 8;

    var i = len - 1;
    while (i > 0) {
        i -= 1;
        dig += @as(u32, d[i]) + @as(u32, a[i]) * b + @as(u32, n[i]) * z;
        d[i + 1] = @truncate(dig);
        dig >>= 8;
    }

    d[0] = @truncate(dig);
    dig >>= 8;

    if (dig != 0) _ = bnSub1(d, d, n);
    bnReduce(d, n);
}

fn bnMonMul(d: []u8, a: []const u8, b: []const u8, n: []const u8) void {
    const len = d.len;
    var t: [32]u8 = @splat(0);
    var i = len;
    while (i > 0) {
        i -= 1;
        bnMonMulAddDig(t[0..len], a, b[i], n);
    }
    @memcpy(d, t[0..len]);
}

fn bnToMon(d: []u8, n: []const u8) void {
    var i: usize = 0;
    while (i < 8 * d.len) : (i += 1) bnAdd(d, d, d, n);
}

fn bnFromMon(d: []u8, n: []const u8) void {
    const len = d.len;
    var t: [32]u8 = @splat(0);
    t[len - 1] = 1;
    bnMonMul(d, d, t[0..len], n);
}

fn bnMonExp(d: []u8, a: []const u8, n: []const u8, e: []const u8) void {
    const len = d.len;
    var t: [32]u8 = undefined;

    @memset(d, 0);
    d[len - 1] = 1;
    bnToMon(d, n);

    for (e) |eb| {
        var mask: u8 = 0x80;
        while (mask != 0) : (mask >>= 1) {
            bnMonMul(t[0..len], d, d, n);
            if ((eb & mask) != 0) {
                bnMonMul(d, t[0..len], a, n);
            } else {
                @memcpy(d, t[0..len]);
            }
        }
    }
}

fn bnMonInv(d: []u8, a: []const u8, n: []const u8) void {
    const len = d.len;
    var t: [32]u8 = undefined;
    var s: [32]u8 = @splat(0);
    s[len - 1] = 2;
    _ = bnSub1(t[0..len], n, s[0..len]);
    bnMonExp(d, a, n, t[0..len]);
}

const Point = struct {
    x: [20]u8,
    y: [20]u8,

    const zero: Point = .{ .x = @splat(0), .y = @splat(0) };

    fn isZero(p: *const Point) bool {
        return eltIsZero(&p.x) and eltIsZero(&p.y);
    }
};

fn eltIsZero(d: *const [20]u8) bool {
    for (d) |b| if (b != 0) return false;
    return true;
}

/// One short-Weierstrass curve over GF(p), with a, b and G in Montgomery form
/// (ecdsa_set_curve). N has a leading zero byte (21 bytes).
const Curve = struct {
    p: [20]u8,
    a: [20]u8,
    b: [20]u8,
    n: [21]u8,
    g: Point,

    fn init(p: [20]u8, a: [20]u8, b: [20]u8, n: [21]u8, gx: [20]u8, gy: [20]u8) Curve {
        var c: Curve = .{ .p = p, .a = a, .b = b, .n = n, .g = .{ .x = gx, .y = gy } };
        bnToMon(&c.a, &c.p);
        bnToMon(&c.b, &c.p);
        c.pointToMon(&c.g);
        return c;
    }

    fn eltAdd(c: *const Curve, d: *[20]u8, a: *const [20]u8, b: *const [20]u8) void {
        bnAdd(d, a, b, &c.p);
    }
    fn eltSub(c: *const Curve, d: *[20]u8, a: *const [20]u8, b: *const [20]u8) void {
        bnSub(d, a, b, &c.p);
    }
    fn eltMul(c: *const Curve, d: *[20]u8, a: *const [20]u8, b: *const [20]u8) void {
        bnMonMul(d, a, b, &c.p);
    }
    fn eltInv(c: *const Curve, d: *[20]u8, a: *const [20]u8) void {
        const s = a.*;
        bnMonInv(d, &s, &c.p);
    }

    fn pointToMon(c: *const Curve, p: *Point) void {
        bnToMon(&p.x, &c.p);
        bnToMon(&p.y, &c.p);
    }
    fn pointFromMon(c: *const Curve, p: *Point) void {
        bnFromMon(&p.x, &c.p);
        bnFromMon(&p.y, &c.p);
    }

    fn pointDouble(c: *const Curve, r: *Point, p: *const Point) void {
        const pp = p.*;
        var s: [20]u8 = undefined;
        var t: [20]u8 = undefined;

        if (eltIsZero(&pp.y)) {
            r.* = Point.zero;
            return;
        }

        c.eltMul(&t, &pp.x, &pp.x);
        c.eltAdd(&s, &t, &t);
        c.eltAdd(&s, &s, &t);
        c.eltAdd(&s, &s, &c.a);
        c.eltAdd(&t, &pp.y, &pp.y);
        c.eltInv(&t, &t);
        c.eltMul(&s, &s, &t);

        c.eltMul(&r.x, &s, &s);
        c.eltAdd(&t, &pp.x, &pp.x);
        c.eltSub(&r.x, &r.x, &t);

        c.eltSub(&t, &pp.x, &r.x);
        c.eltMul(&r.y, &s, &t);
        c.eltSub(&r.y, &r.y, &pp.y);
    }

    fn pointAdd(c: *const Curve, r: *Point, p: *const Point, q: *const Point) void {
        const pp = p.*;
        const qq = q.*;
        var s: [20]u8 = undefined;
        var t: [20]u8 = undefined;
        var u: [20]u8 = undefined;

        if (pp.isZero()) {
            r.x = qq.x;
            r.y = qq.y;
            return;
        }
        if (qq.isZero()) {
            r.x = pp.x;
            r.y = pp.y;
            return;
        }

        c.eltSub(&u, &qq.x, &pp.x);
        if (eltIsZero(&u)) {
            c.eltSub(&u, &qq.y, &pp.y);
            if (eltIsZero(&u)) {
                c.pointDouble(r, &pp);
            } else {
                r.* = Point.zero;
            }
            return;
        }

        c.eltInv(&t, &u);
        c.eltSub(&u, &qq.y, &pp.y);
        c.eltMul(&s, &t, &u);

        c.eltMul(&r.x, &s, &s);
        c.eltAdd(&t, &pp.x, &qq.x);
        c.eltSub(&r.x, &r.x, &t);

        c.eltSub(&t, &pp.x, &r.x);
        c.eltMul(&r.y, &s, &t);
        c.eltSub(&r.y, &r.y, &pp.y);
    }

    /// `a` is a 21-byte big-endian scalar.
    fn pointMul(c: *const Curve, d: *Point, a: *const [21]u8, b: *const Point) void {
        d.* = Point.zero;
        for (a) |ab| {
            var mask: u8 = 0x80;
            while (mask != 0) : (mask >>= 1) {
                c.pointDouble(d, d);
                if ((ab & mask) != 0) c.pointAdd(d, d, b);
            }
        }
    }

    /// check_ecdsa: `q` is already in Montgomery form (ecdsa_set_pub).
    fn verify(c: *const Curve, q: *const Point, R: *const [20]u8, S: *const [20]u8, hash: *const [20]u8) bool {
        var e: [21]u8 = undefined;
        var r: [21]u8 = undefined;
        var s: [21]u8 = undefined;
        var rr: [21]u8 = undefined;
        var sinv: [21]u8 = undefined;
        var w1: [21]u8 = undefined;
        var w2: [21]u8 = undefined;
        var p1: Point = undefined;
        var p2: Point = undefined;

        e[0] = 0;
        r[0] = 0;
        s[0] = 0;
        rr[0] = 0;
        @memcpy(e[1..], hash);
        @memcpy(r[1..], R);
        @memcpy(s[1..], S);
        // 0 < r,s < N, never reduced into range.
        if (eltIsZero(R) or eltIsZero(S) or bnCompare(&r, &c.n) >= 0 or bnCompare(&s, &c.n) >= 0) return false;
        bnReduce(&e, &c.n);

        bnToMon(&r, &c.n);
        bnToMon(&s, &c.n);
        bnToMon(&e, &c.n);
        bnMonInv(&sinv, &s, &c.n);
        bnMonMul(&w1, &e, &sinv, &c.n);
        bnMonMul(&w2, &r, &sinv, &c.n);
        bnFromMon(&w1, &c.n);
        bnFromMon(&w2, &c.n);

        c.pointMul(&p1, &w1, &c.g);
        c.pointMul(&p2, &w2, q);
        c.pointAdd(&p1, &p1, &p2);
        if (p1.isZero()) return false;
        c.pointFromMon(&p1);
        @memcpy(rr[1..], &p1.x);
        bnReduce(&rr, &c.n);
        bnFromMon(&r, &c.n);

        return bnCompare(&rr, &r) == 0;
    }
};

