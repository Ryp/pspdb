// ------------------------------------------------------------------ KIRK commands

/// kirk_cmd1_size: validates the whole CBC block and CMAC span up front.
fn cmd1Size(in: []const u8) i32 {
    const size: usize = @min(in.len, std.math.maxInt(i32));
    if (size < cmd1_header_size) return KIRK_INVALID_SIZE;
    const data_size = rd32(in, 0x70);
    const data_offset = rd32(in, 0x74);
    if (data_size == 0) return KIRK_DATA_SIZE_ZERO;
    var available: u32 = @intCast(size - cmd1_header_size);
    if (data_offset > available) return KIRK_INVALID_SIZE;
    available -= data_offset;
    if (data_size > available) return KIRK_INVALID_SIZE;
    const rounded = (data_size + 15) & ~@as(u32, 15);
    if (rounded > available) return KIRK_INVALID_SIZE;
    return KIRK_OPERATION_SUCCESS;
}

/// kirk_CMD1 (size = in.len). Writes `ceil16(data_size)` bytes to `out`
/// (the C writes the full final block too); too-small `out` returns
/// KIRK_INVALID_SIZE where the C would overflow.
pub fn cmd1(out: []u8, in: []const u8) i32 {
    const bounds = cmd1Size(in);
    if (bounds != KIRK_OPERATION_SUCCESS) return bounds;
    if (rd32(in, 0x60) != KIRK_MODE_CMD1) return KIRK_INVALID_MODE;

    var keys: [32]u8 = undefined; // AES key, CMAC key
    cbcDecrypt(&kirk1_key, &keys, in[0..32], 2);

    const data_size = rd32(in, 0x70);
    const data_offset: usize = rd32(in, 0x74);
    const cipher_size: usize = (data_size + 15) & ~@as(u32, 15);

    if (in[0x64] == 1) {
        // ECDSA mode: fixed KIRK1 public key; header and data signatures are verified.
        const curve = Curve.init(ec_p, ec_a, ec_b1, ec_n1, gx1, gy1);
        var q: Point = .{ .x = px1, .y = py1 };
        curve.pointToMon(&q);

        var hash: [20]u8 = undefined;
        Sha1.hash(in[0x60..][0..0x30], &hash, .{});
        if (!curve.verify(&q, in[0x10..][0..20], in[0x24..][0..20], &hash)) return KIRK_HEADER_HASH_INVALID;

        // Signed span: metadata, predata and every CBC block.
        Sha1.hash(in[0x60..][0 .. 0x30 + data_offset + cipher_size], &hash, .{});
        if (!curve.verify(&q, in[0x38..][0..20], in[0x4C..][0..20], &hash)) return KIRK_DATA_HASH_INVALID;
    } else {
        const ret = cmd10(in);
        if (ret != KIRK_OPERATION_SUCCESS) return ret;
    }

    if (out.len < cipher_size) return KIRK_INVALID_SIZE;
    cbcDecrypt(keys[0..16], out, in[cmd1_header_size + data_offset ..], cipher_size / 16);
    return KIRK_OPERATION_SUCCESS;
}

/// kirk_CMD10: CMAC check for mode-1 headers; modes 2/3 are not implemented upstream.
pub fn cmd10(in: []const u8) i32 {
    const bounds = cmd1Size(in);
    if (bounds != KIRK_OPERATION_SUCCESS) return bounds;
    const mode = rd32(in, 0x60);
    if (!(mode == KIRK_MODE_CMD1 or mode == KIRK_MODE_CMD2 or mode == KIRK_MODE_CMD3)) return KIRK_INVALID_MODE;
    const data_size = rd32(in, 0x70);
    if (data_size == 0) return KIRK_DATA_SIZE_ZERO;

    if (mode == KIRK_MODE_CMD1) {
        var keys: [32]u8 = undefined;
        cbcDecrypt(&kirk1_key, &keys, in[0..32], 2);
        const chk_size: usize = (data_size + 15) & ~@as(u32, 15);
        const data_offset: usize = rd32(in, 0x74);

        var header_hash: [16]u8 = undefined;
        var data_hash: [16]u8 = undefined;
        CmacAes128.create(&header_hash, in[0x60..][0..0x30], keys[16..32]);
        CmacAes128.create(&data_hash, in[0x60..][0 .. 0x30 + chk_size + data_offset], keys[16..32]);

        if (!std.mem.eql(u8, &header_hash, in[0x20..][0..16])) return KIRK_HEADER_HASH_INVALID;
        if (!std.mem.eql(u8, &data_hash, in[0x30..][0..16])) return KIRK_DATA_HASH_INVALID;
        return KIRK_OPERATION_SUCCESS;
    }
    return KIRK_SIG_CHECK_INVALID;
}

/// kirk_CMD4: header {mode=4, _, _, keyseed, data_size}; encrypts blocks at +0x14 to out+0x14.
pub fn cmd4(out: []u8, in: []const u8) i32 {
    if (in.len < 0x14) return KIRK_INVALID_SIZE; // C reads the header unchecked
    if (rd32(in, 0) != KIRK_MODE_ENCRYPT_CBC) return KIRK_INVALID_MODE;
    const data_size = rdi32(in, 0x10);
    if (data_size == 0) return KIRK_DATA_SIZE_ZERO;
    const key = kirk47GetKey(rdi32(in, 0xC)) orelse return KIRK_INVALID_SIZE;

    // AES_cbc_encrypt loops `for (i = 0; i < size; i += 16)`: nothing for size < 0.
    const nb: usize = if (data_size > 0) blocksCeil(@intCast(data_size)) else 0;
    if (in.len - 0x14 < nb * 16 or out.len < 0x14 or out.len - 0x14 < nb * 16) return KIRK_INVALID_SIZE;
    cbcEncrypt(key, out[0x14..], in[0x14..], nb);
    return KIRK_OPERATION_SUCCESS;
}

/// kirk_CMD7: header {mode=5, _, _, keyseed, data_size}; decrypts blocks at +0x14 to `out`.
pub fn cmd7(out: []u8, in: []const u8) i32 {
    if (in.len < 0x14) return KIRK_INVALID_SIZE; // C reads the header unchecked
    if (rd32(in, 0) != KIRK_MODE_DECRYPT_CBC) return KIRK_INVALID_MODE;
    const data_size = rdi32(in, 0x10);
    if (data_size == 0) return KIRK_DATA_SIZE_ZERO;
    const key = kirk47GetKey(rdi32(in, 0xC)) orelse return KIRK_INVALID_SIZE;

    // AES_cbc_decrypt always processes the first block, even for negative sizes.
    const nb: usize = if (data_size > 0) blocksCeil(@intCast(data_size)) else 1;
    if (in.len - 0x14 < nb * 16 or out.len < nb * 16) return KIRK_INVALID_SIZE;
    cbcDecrypt(key, out, in[0x14..], nb);
    return KIRK_OPERATION_SUCCESS;
}

/// kirk_CMD11: header {u32 data_size}; SHA-1 of the following bytes into out[0..20].
pub fn cmd11(out: []u8, in: []const u8) i32 {
    if (in.len < 4) return KIRK_DATA_SIZE_ZERO;
    const data_size = rd32(in, 0);
    if (data_size == 0) return KIRK_DATA_SIZE_ZERO;
    if (data_size > in.len - 4 or out.len < 20) return KIRK_INVALID_SIZE; // C overreads/overwrites
    Sha1.hash(in[4..][0..data_size], out[0..20], .{});
    return KIRK_OPERATION_SUCCESS;
}

/// kirk_CMD17: ECDSA verify of {pub x||y (0x28), hash (0x14), r (0x14), s (0x14)} on the KIRK17 curve.
pub fn cmd17(in: []const u8) i32 {
    if (in.len != 0x64) return KIRK_INVALID_SIZE;
    const curve = Curve.init(ec_p, ec_a, ec_b2, ec_n2, gx2, gy2);
    var q: Point = .{ .x = in[0..20].*, .y = in[20..40].* };
    curve.pointToMon(&q);
    if (curve.verify(&q, in[0x3C..][0..20], in[0x50..][0..20], in[0x28..][0..20])) return KIRK_OPERATION_SUCCESS;
    return KIRK_SIG_CHECK_INVALID;
}

/// `sceUtilsBufferCopyWithRange(out, out.len, in, in.len, cmd)`. `out` and `in`
/// may alias. cmd 12/13/14/16 and every unlisted cmd (including 5 and 8, which
/// amctrl relies on failing) return -1, the C default.
pub fn bufferCopyWithRange(out: []u8, in: []const u8, cmd: i32) i32 {
    return switch (cmd) {
        KIRK_CMD_DECRYPT_PRIVATE => cmd1(out, in),
        KIRK_CMD_ENCRYPT_IV_0 => cmd4(out, in),
        KIRK_CMD_DECRYPT_IV_0 => cmd7(out, in),
        KIRK_CMD_PRIV_SIGN_CHECK => cmd10(in),
        KIRK_CMD_SHA1_HASH => cmd11(out, in),
        KIRK_CMD_ECDSA_VERIFY => cmd17(in),
        else => -1,
    };
}
